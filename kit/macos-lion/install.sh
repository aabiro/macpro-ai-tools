#!/bin/bash
# install.sh -- install the AI Cockpit on Mac OS X 10.7 Lion.
#
# Installs to /Users/Shared/ai-cockpit so that EVERY account on this Mac can
# use it, including accounts created after the machine changes hands. Nothing
# here needs administrator rights.
#
#     ./install.sh
#
# Re-running it is safe; it overwrites the programs and leaves your settings
# (~/.g5ai.json) alone.

set -u

DEST="/Users/Shared/ai-cockpit"
BIN="$DEST/bin"
SRC="$(cd "$(dirname "$0")" && pwd)"

echo "Installing the AI Cockpit to $DEST"

mkdir -p "$BIN" "$DEST/gateway" "$DEST/docs" || {
    echo "Could not create $DEST -- check permissions on /Users/Shared" >&2
    exit 1
}

# --- programs -------------------------------------------------------------
for f in g5ai.py cockpit.py g5_config.py g5_doctor.py g5_assist.py retro_port.py; do
    if [ -f "$SRC/$f" ]; then
        cp "$SRC/$f" "$DEST/$f" && chmod 644 "$DEST/$f"
    else
        echo "  warning: $f not found next to install.sh" >&2
    fi
done

# --- machine-wide config template ----------------------------------------
# Only written if absent, so a re-run never clobbers a working gateway address.
if [ ! -f "$DEST/config.json" ]; then
    cat > "$DEST/config.json" <<'JSON'
{
  "gateway": "",
  "provider": "gemini",
  "model": "",
  "max_tokens": 2048,
  "timeout": 120
}
JSON
    chmod 666 "$DEST/config.json" 2>/dev/null || true
fi

# --- command wrappers -----------------------------------------------------
# Each wrapper pins PYTHONPATH so the modules resolve no matter where you cd to.
make_wrapper() {
    name="$1"; module="$2"
    cat > "$BIN/$name" <<WRAP
#!/bin/bash
# AI Cockpit launcher -- generated by install.sh
export PYTHONPATH="$DEST:\${PYTHONPATH:-}"
exec /usr/bin/python "$DEST/$module" "\$@"
WRAP
    chmod 755 "$BIN/$name"
}

make_wrapper cockpit     cockpit.py
make_wrapper g5-config   g5_config.py
make_wrapper g5-doctor   g5_doctor.py
make_wrapper g5-assist   g5_assist.py
make_wrapper retro-port  retro_port.py

# --- put the commands on PATH --------------------------------------------
PROFILE="$HOME/.bash_profile"
LINE="export PATH=\"$BIN:\$PATH\"   # AI Cockpit"
if [ -f "$PROFILE" ] && grep -q "AI Cockpit" "$PROFILE" 2>/dev/null; then
    echo "  PATH already set up in $PROFILE"
else
    echo "" >> "$PROFILE"
    echo "# Added by the AI Cockpit installer" >> "$PROFILE"
    echo "$LINE" >> "$PROFILE"
    echo "  Added $BIN to PATH in $PROFILE"
fi

echo ""
echo "Installed. Commands available:"
echo "    cockpit                 full-screen interface"
echo "    g5-config show|test     settings and connection check"
echo "    g5-doctor               machine health report"
echo "    g5-assist \"...\"         plain English to a shell command"
echo "    retro-port FILE         back-port code to build here"
echo ""
echo "Open a NEW Terminal window (or run: source $PROFILE), then:"
echo "    g5-config show"
echo ""
